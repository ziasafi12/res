// Lightweight, dependency-free API integration tests against the configured
// database. Intended for local verification after `npm run seed`.
import assert from "node:assert/strict";
import { createApp } from "./src/app.js";
import { checkConnection, pool } from "./src/db.js";

let server;
let baseUrl;
let testFoodId;

async function request(path, { method = "GET", body, cookie } = {}) {
  const response = await fetch(`${baseUrl}${path}`, {
    method,
    headers: {
      ...(body ? { "Content-Type": "application/json" } : {}),
      ...(cookie ? { Cookie: cookie } : {})
    },
    body: body ? JSON.stringify(body) : undefined
  });
  const data = await response.json();
  const setCookie = response.headers.get("set-cookie");
  return { response, data, cookie: setCookie ? setCookie.split(";")[0] : undefined };
}

try {
  await checkConnection();
  const app = createApp();
  server = await new Promise((resolve) => {
    const s = app.listen(0, "127.0.0.1", () => resolve(s));
  });
  baseUrl = `http://127.0.0.1:${server.address().port}`;

  // Public endpoint and unauthenticated protection.
  const publicFoods = await request("/api/foods");
  assert.equal(publicFoods.response.status, 200);
  assert.ok(publicFoods.data.foods.length > 0);
  const unauthFoods = await request("/api/foods", {
    method: "POST",
    body: { name: "Blocked", price: 1, category: "Test" }
  });
  assert.equal(unauthFoods.response.status, 401);
  const unauthInvoices = await request("/api/invoices");
  assert.equal(unauthInvoices.response.status, 401);

  // Bad login is rejected; valid admin/client logins create cookie sessions.
  const badLogin = await request("/api/login", {
    method: "POST",
    body: { username: "admin", password: "wrong" }
  });
  assert.equal(badLogin.response.status, 401);
  const adminLogin = await request("/api/login", {
    method: "POST",
    body: { username: "admin", password: "Administrator@24" }
  });
  assert.equal(adminLogin.response.status, 200);
  assert.equal(adminLogin.data.user.role, "admin");
  assert.ok(adminLogin.cookie);
  const clientLogin = await request("/api/login", {
    method: "POST",
    body: { username: "client", password: "client@25" }
  });
  assert.equal(clientLogin.response.status, 200);
  assert.equal(clientLogin.data.user.role, "client");
  assert.ok(clientLogin.cookie);

  // Client must never manage foods (real backend RBAC, not just hidden UI).
  const clientCreateFood = await request("/api/foods", {
    method: "POST",
    cookie: clientLogin.cookie,
    body: { name: "Blocked Client Food", price: 1, category: "Test" }
  });
  assert.equal(clientCreateFood.response.status, 403);

  // Admin food CRUD.
  const uniqueName = `API Test Food ${Date.now()}`;
  const createFood = await request("/api/foods", {
    method: "POST",
    cookie: adminLogin.cookie,
    body: {
      name: uniqueName,
      description: "Temporary integration-test menu item",
      price: 4.25,
      category: "Test",
      image: "",
      availability: true
    }
  });
  assert.equal(createFood.response.status, 201);
  testFoodId = createFood.data.food.id;
  const updateFood = await request(`/api/foods/${testFoodId}`, {
    method: "PUT",
    cookie: adminLogin.cookie,
    body: {
      name: uniqueName,
      description: "Updated temporary item",
      price: 5.5,
      category: "Test",
      image: "",
      availability: true
    }
  });
  assert.equal(updateFood.response.status, 200);
  assert.equal(updateFood.data.food.price, 5.5);

  // Client invoice: price and total are taken/calculated on server, not from
  // values supplied by the browser. Invoice number is generated by sequence.
  const invoiceOne = await request("/api/invoices", {
    method: "POST",
    cookie: clientLogin.cookie,
    body: { customer_name: "Integration Test Customer", food_id: testFoodId, quantity: 3, price: 0.01 }
  });
  assert.equal(invoiceOne.response.status, 201);
  assert.equal(invoiceOne.data.invoice.price, 5.5);
  assert.equal(invoiceOne.data.invoice.total, 16.5);
  assert.match(invoiceOne.data.invoice.invoice_number, /^INV-\d+$/);

  const invoiceTwo = await request("/api/invoices", {
    method: "POST",
    cookie: clientLogin.cookie,
    body: { customer_name: "Integration Test Customer", food_id: testFoodId, quantity: 1 }
  });
  assert.equal(invoiceTwo.response.status, 201);
  assert.notEqual(invoiceOne.data.invoice.invoice_number, invoiceTwo.data.invoice.invoice_number);

  const clientInvoices = await request("/api/invoices", { cookie: clientLogin.cookie });
  assert.equal(clientInvoices.response.status, 200);
  assert.ok(clientInvoices.data.invoices.some((i) => i.id === invoiceOne.data.invoice.id));

  // An unavailable item cannot be invoiced even via direct API call.
  const hideFood = await request(`/api/foods/${testFoodId}`, {
    method: "PUT",
    cookie: adminLogin.cookie,
    body: { name: uniqueName, description: "Updated temporary item", price: 5.5, category: "Test", availability: false }
  });
  assert.equal(hideFood.response.status, 200);
  const hiddenInvoice = await request("/api/invoices", {
    method: "POST",
    cookie: clientLogin.cookie,
    body: { customer_name: "Integration Test Customer", food_id: testFoodId, quantity: 1 }
  });
  assert.equal(hiddenInvoice.response.status, 400);

  // Logout deletes the session cookie.
  const logout = await request("/api/logout", { method: "POST", cookie: clientLogin.cookie });
  assert.equal(logout.response.status, 200);

  console.log("API integration tests passed.");
} finally {
  if (testFoodId) {
    await pool.query("DELETE FROM foods WHERE id = $1", [testFoodId]).catch(() => {});
  }
  await new Promise((resolve) => (server ? server.close(resolve) : resolve()));
  await pool.end();
}